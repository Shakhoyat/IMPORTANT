"""v9 M3: writes the ThermalSense.exe input scripts of the motor / camera session.

  m3_session.txt  the session with dense 'log' lines (speed response curves) and a few key shots
  m3_video.txt    the same inputs with a 'shot' every 0.1 s instead (960x540 frames for docs/v9_notes/m3/m3_session.mp4)

F3 takes the sentry by the gate (seed 1, 10:30: feet (-3.7, -0.3, 25.2), heading -30), V = first person. First-person
turns use the held arrow keys (60 deg/s, deterministic; a right turn lowers the heading, 0 = +z north, 90 = +x): the
scripted mouse moves of the real exe can be offset by a real cursor event, so the mouse is only used for the
third-person orbit. The road barrier at x = -2.95, z 21..24 (0.30 m base step, top 0.55 m above it) is the step /
jump-over obstacle.
"""
import sys


def session(dense_shots):
    ev = []

    def at(t, cmd):
        ev.append((round(t, 3), cmd))

    def logs(t0, t1, step, label):
        k, t = 0, t0
        while t <= t1 + 1e-9:
            at(t, f"log {label}_{k:02d}")
            k += 1
            t += step

    def hold(key, t0, t1):
        at(t0, f"key {key} down")
        at(t1, f"key {key} up")

    at(5.0, "key F3 tap")
    at(6.0, "key V tap")                  # first person
    at(7.0, "log fp_start")
    # 1) walk (heading -30, north-west): rise and stop of the speed response
    hold("W", 7.5, 9.0)
    logs(7.5, 8.1, 0.05, "walk_rise")
    logs(9.0, 9.5, 0.05, "walk_stop")
    # 2) turn to the south (150 deg right), walk to the barrier's row (z ~ 22.5)
    hold("RIGHT", 9.8, 12.3)
    at(12.4, "log turned_south")
    hold("W", 12.5, 15.7)
    at(15.8, "log at_row")
    # 3) turn east (90 deg right): a running jump onto the barrier (0.85 m above the ground: a standing jump into it does
    # not clear it), off its far side onto the 0.30 m base step and down onto the road
    hold("RIGHT", 16.0, 17.5)
    at(17.6, "log face_barrier")
    at(17.8, "key SHIFT down")
    hold("W", 17.8, 19.6)
    at(19.6, "key SHIFT up")
    at(18.25, "key SPACE tap")
    logs(17.8, 19.8, 0.05, "jump")
    at(21.1, "log on_road")
    # 4) turn south again (90 deg left) and sprint down the road: rise, FOV kick, stop
    hold("LEFT", 21.3, 22.8)
    at(22.9, "log face_south")
    at(23.0, "key SHIFT down")
    hold("W", 23.0, 24.5)
    at(24.5, "key SHIFT up")
    logs(23.0, 23.6, 0.05, "sprint_rise")
    logs(24.5, 25.0, 0.05, "sprint_stop")
    # 5) turn back north (180 deg), crouch (Left Alt), crouch walk, stand
    hold("RIGHT", 25.1, 28.1)
    at(28.3, "key LEFT_ALT tap")
    logs(28.3, 28.6, 0.05, "crouch_blend")
    hold("W", 28.8, 30.2)
    logs(29.0, 30.0, 0.2, "crouch_walk")
    at(30.4, "key LEFT_ALT tap")
    logs(30.4, 30.7, 0.05, "stand_blend")
    # 6) jump, and a second press ~0.1 s before touching down: buffered, it fires on landing
    at(31.0, "key SPACE tap")
    at(31.5, "key SPACE tap")
    logs(31.0, 32.5, 0.05, "buffer_jump")
    # 7) west along z ~ 19.5 (south of the barrier's end), then north beside it to (-3.35, 21.2): third person, a full
    # orbit next to the barrier and its post (the arm pulls in and eases back out)
    hold("RIGHT", 32.6, 34.1)
    hold("W", 34.2, 36.9)
    hold("LEFT", 37.0, 38.5)
    hold("W", 38.6, 40.0)
    at(40.1, "log at_barrier")
    at(40.3, "key V tap")
    at(41.1, "look 2400 0 4.0")           # full orbit
    logs(41.1, 45.1, 0.25, "orbit")
    # 8) third-person walk with a camera swing (the body turns into it), then sprint + jump
    hold("W", 45.5, 47.7)
    at(46.2, "look -500 0 0.8")
    logs(45.5, 47.7, 0.25, "tp_walk")
    at(48.1, "key SHIFT down")
    hold("W", 48.1, 49.9)
    at(49.9, "key SHIFT up")
    at(48.9, "key SPACE tap")
    logs(48.1, 49.9, 0.1, "tp_sprint_jump")
    at(50.6, "quit")
    if dense_shots:
        t, k = 6.2, 0
        while t < 50.5:
            at(t, f"shot v{k:04d}")
            k += 1
            t += 0.1
    else:
        for t, name in [(7.0, "m3_00_fp_start"), (8.6, "m3_01_fp_walk"), (17.6, "m3_02_fp_barrier"), (18.35, "m3_03_fp_jump"),
                        (18.8, "m3_04_fp_over_barrier"), (21.1, "m3_05_fp_on_road"), (24.2, "m3_06_fp_sprint_fov"),
                        (29.8, "m3_07_fp_crouch_walk"), (40.1, "m3_08_fp_at_barrier"), (42.1, "m3_09_tp_orbit_a"),
                        (43.1, "m3_10_tp_orbit_b"), (44.1, "m3_11_tp_orbit_c"), (45.1, "m3_12_tp_orbit_d"), (47.2, "m3_13_tp_walk_turn"),
                        (49.15, "m3_14_tp_sprint_jump")]:
            at(t, f"shot {name}")
    ev.sort(key=lambda e: e[0])
    head = "# v9 M3 motor / camera session (generated by docs/v9_notes/m3/make_scripts.py)\n"
    return head + "".join(f"{t:.3f} {c}\n" for t, c in ev)


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    open(f"{out}/m3_session.txt", "w").write(session(False))
    open(f"{out}/m3_video.txt", "w").write(session(True))
