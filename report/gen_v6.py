rows.append("thigh / shin / hip height (m) & \\multicolumn{2}{c}{%.2f / %.2f / %.2f}\\\\" % (gw["thigh"], gw["shin"], gw["hip_height"]))
table("Gait", "\\begin{tabular}{@{}lrr@{}}\\toprule\nParameter & Walk & Run\\\\\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\\end{tabular}")
