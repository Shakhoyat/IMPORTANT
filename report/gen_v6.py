for k, nd in (("netdDn", 1), ("fpnGainSigma", 2), ("fpnOffsetSigma", 1), ("columnSigma", 1), ("jitterDeg", 2),
              ("dropProb", 2), ("nucResidual", 2), ("cvFloor", 0), ("cvCore", 0)):
    macro("sn" + k[0].upper() + k[1:], fmt(sn[k]["value"], nd))
