table("Seeds", "\\begin{tabular}{@{}lrr@{}}\\toprule\nStream & $k$ & \\code{deriveSeed(%d, k)}\\\\\\midrule\n" % sd["example_base"]
      + "\n".join(rows) + "\n\\bottomrule\\end{tabular}")
