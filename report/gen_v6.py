def load(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return json.load(f)


def esc(s):
    s = str(s)
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}"}
    s = "".join(rep.get(c, c) for c in s)
    for a, b in (("°", r"$^\circ$"), ("±", r"$\pm$"), ("→", r"$\rightarrow$"), ("×", r"$\times$"),
                 ("≤", r"$\le$"), ("≥", r"$\ge$"), ("≈", r"$\approx$"), ("–", "--"), ("—", "---"),
                 ("−", "-"), ("²", r"$^2$"), ("σ", r"$\sigma$"), ("κ", r"$\kappa$")):
        s = s.replace(a, b)
    return s.encode("ascii", "replace").decode("ascii")


def clock(h):
    m = int(round(h * 60)) % 1440
    return "%02d:%02d" % (m // 60, m % 60)


L = ["% generated by report/gen_v6.py -- do not edit"]


def macro(name, value):
    assert re.fullmatch(r"[A-Za-z]+", name), name
    L.append("\\newcommand{\\%s}{%s}" % (name, value))


def table(name, body):
    """\\tabNAME expands to a tabular (used inside table / figure environments)."""
    macro("tab" + name, "%\n" + body)


def fmt(v, nd=2):
    return ("%%.%df" % nd) % v


