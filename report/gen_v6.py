for k, nd in (("kSpawnJitter", 1), ("kNorthGapDeg", 0), ("kViaSectorDeg", 0), ("kViaMinR", 0), ("kViaMaxR", 0),
              ("kMaxVia", 0), ("kSwitchProbability", 1), ("kSwitchMinS", 0), ("kSwitchMaxS", 0)):
    macro("rr" + k[1:], fmt(rr[k]["value"], nd))
