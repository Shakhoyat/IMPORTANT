SUBS = {
    "\u00b0": r"$^\circ$", "\u00b1": r"$\pm$", "\u2192": r"$\rightarrow$", "\u00d7": r"$\times$",
    "\u2264": r"$\leq$", "\u2265": r"$\geq$", "\u2248": r"$\approx$", "\u03c0": r"$\pi$",
    "\u00b5": r"$\mu$", "\u2013": "--", "\u2014": "---", "\u2212": "-", "\u00b2": r"$^2$",
}


def esc(s, width=None, brk=True):
    s = str(s)
    if width and len(s) > width:
        s = s[: width - 3].rstrip() + "..."
    for k, v in SUBS.items():
        s = s.replace(k, "\x00" + v + "\x01")
    out = []
    mathdepth = False
    i = 0
    # protect the substitutions, escape everything else
    parts = re.split("(\x00.*?\x01)", s)
    for p in parts:
        if p.startswith("\x00"):
            out.append(p[1:-1])
            continue
        p = p.encode("ascii", "replace").decode("ascii")
        p = p.replace("\\", r"\textbackslash{}")
        for ch in "&%$#_{}":
            p = p.replace(ch, "\\" + ch)
        p = p.replace("~", r"\textasciitilde{}").replace("^", r"\textasciicircum{}")
        p = p.replace("<", r"\textless{}").replace(">", r"\textgreater{}").replace("|", r"\textbar{}")
        # allow line breaks after commas and slashes inside long strings
        if brk:
            p = p.replace(",", r",\allowbreak{}").replace("/", r"/\allowbreak{}")
        out.append(p)
    return "".join(out)


