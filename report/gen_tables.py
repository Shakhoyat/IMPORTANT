def leaf_count(x):
    if x["primitive"] != "Group":
        return 1
    return sum(leaf_count(y) for y in children[x["id"]])


def stem(name):
    n = re.sub(r"\s+[A-Z]?\d+$", "", name)
    n = re.sub(r"\s+[A-Za-z]\d+( [a-z]\d+)?$", "", n)
    n = re.sub(r"\s+\d+$", "", n)
    return n


def tree_rows(root, maxdepth):
    rows = []

    def visit(x, depth, mult):
        n = leaf_count(x)
        label = x["name"] if mult == 1 else "%s $\\times$%d" % (esc(x["name"], brk=False), mult)
        label = esc(x["name"], brk=False) if mult == 1 else label
        each = " each" if mult > 1 else ""
        rows.append((depth, "%s \\textcolor{black!55}{[%d%s]}" % (label, n, each)))
        if depth >= maxdepth:
            return
        kids = children[x["id"]]
        groups = [k for k in kids if k["primitive"] == "Group"]
        leaves = [k for k in kids if k["primitive"] != "Group"]
        # direct parts, grouped by stem (largest first)
        if leaves:
            stems = collections.Counter(stem(k["name"]) for k in leaves)
            top = ", ".join("%s $\\times$%d" % (esc(k, brk=False), v) if v > 1 else esc(k, brk=False)
                            for k, v in stems.most_common(2))
            more = len(stems) - 2
            rows.append((depth + 1, "\\textit{%d direct parts: %s%s}" % (len(leaves), top, ", ..." if more > 0 else "")))
        i = 0
        while i < len(groups):
            j = i
            while j + 1 < len(groups) and groups[j + 1]["name"] == groups[i]["name"] and leaf_count(groups[j + 1]) == leaf_count(groups[i]):
                j += 1
            visit(groups[i], depth + 1, j - i + 1)
            i = j + 1

    visit(root, 0, 1)
    return rows


def write_tree(fname, root_name, maxdepth, obj=None):
    roots = [x for x in comps if x["name"] == root_name and (obj is None or x["object"] == obj)]
    root = roots[0]
    rows = tree_rows(root, maxdepth)
    with open(os.path.join(OUT, fname), "w", encoding="utf-8") as f:
        f.write("% generated by report/gen_tables.py from build/scene_export.json -- do not edit\n")
        f.write("\\begin{tikzpicture}[x=0.36cm,y=-0.33cm,font=\\scriptsize]\n")
        last = {}
        for i, (d, text) in enumerate(rows):
            f.write("\\node[anchor=west,inner sep=0pt] (n%d) at (%d,%d) {%s};\n" % (i, d, i, text))
            if d > 0:
                p = last[d - 1]
                f.write("\\draw[black!50,thin] (%.2f,%.2f) |- (%.2f,%d);\n" % (p[0] + 0.25, p[1] + 0.35, d - 0.12, i))
            last[d] = (d, i)
        f.write("\\end{tikzpicture}\n")


