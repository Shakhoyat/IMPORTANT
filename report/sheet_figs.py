#!/usr/bin/env python3
"""Turns report/sheets/captions.json (written by tools/xlsx_snapshot.py) into sections/gen_sheets.tex.
For every workbook snapshot it defines a caption macro, so the report's captions always name the real sheet and
cell range of the screenshot:
    \\sheetcaption{s03_uav}   -> "Workbook sheet <sheet>, cells <range>: <caption>"
    \\sheetfig{s03_uav}       -> a full-width figure with that caption and label fig:sheet:s03_uav
Run after xlsx_snapshot.py:  python3 report/sheet_figs.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(HERE, "sheets", "captions.json")
out = os.path.join(HERE, "sections", "gen_sheets.tex")


def tex(s):
    s = str(s)
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    s = "".join(rep.get(ch, ch) for ch in s)
    s = s.replace("×", r"$\times$").replace("·", r"$\cdot$").replace("≤", r"$\le$").replace("≥", r"$\ge$")
    s = s.replace("°", r"$^\circ$").replace("→", r"$\to$").replace(">", r"\textgreater{}").replace("<", r"\textless{}")
    s = s.replace("−", "-").replace("–", "--").replace("—", "---")
    return s


lines = ["% generated by report/sheet_figs.py from sheets/captions.json -- do not edit",
         r"\providecommand{\sheetcaption}[1]{\ifcsname sheetcap@#1\endcsname\csname sheetcap@#1\endcsname\else\texttt{#1}\fi}",
         r"\providecommand{\sheetfig}[2][\linewidth]{\begin{figure}[htbp]\centering\picsheet{#2}{#1}"
         r"\caption{\sheetcaption{#2}}\label{fig:sheet:#2}\end{figure}}"]
caps = json.load(open(src)) if os.path.exists(src) else {}
for key, e in sorted(caps.items()):
    if not re.fullmatch(r"[A-Za-z0-9_]+", key):
        continue
    sheet = tex(e.get("sheet", ""))
    rng = tex(e.get("range", ""))
    cap = tex(e.get("caption", "")).rstrip()
    body = r"Workbook sheet \emph{%s}, cells \texttt{%s}: %s" % (sheet, rng, cap)
    lines.append(r"\expandafter\def\csname sheetcap@%s\endcsname{%s}" % (key, body))
# Diagrams (tools/make_figures.py) and lab renders (--only lab_*): \autofig{dir}{name} with the caption and the
# source / method the producing tool recorded in <dir>/captions.json.
lines.append(r"\providecommand{\autocaption}[2]{\ifcsname figcap@#1@#2\endcsname\csname figcap@#1@#2\endcsname\else\texttt{#2}\fi}")
lines.append(r"\providecommand{\autofig}[3][\linewidth]{\begin{figure}[htbp]\centering\pic{#2/#3}{#1}"
             r"\caption{\autocaption{#2}{#3}}\label{fig:#2:#3}\end{figure}}")
for d, extra in (("diagrams", "source"), ("figures_lab", "how")):
    f = os.path.join(HERE, d, "captions.json")
    if not os.path.exists(f):
        continue
    for name, e in sorted(json.load(open(f)).items()):
        key = os.path.splitext(name)[0]
        if not re.fullmatch(r"[A-Za-z0-9_]+", key) or not isinstance(e, dict):
            continue
        body = tex(e.get("caption", "")).rstrip()
        if e.get(extra):
            body += r" {\footnotesize(%s: \texttt{%s})}" % ("Source" if extra == "source" else "Rendered", tex(e[extra]))
        lines.append(r"\expandafter\def\csname figcap@%s@%s\endcsname{%s}" % (d, key, body))
open(out, "w").write("\n".join(lines) + "\n")
print("wrote %s (%d captions)" % (os.path.relpath(out, HERE), len(caps)))
