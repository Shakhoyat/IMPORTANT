"""Writes report/prim_colors.tex from src/report/PrimitiveColors.h (the only place the primitive colours are defined):
  \\definecolor{prim-<key>}{RGB}{r,g,b}   one per primitive
  \\primsq{<key>}                          the colour square alone
  \\primchip{<key>}                        square + name (e.g. \\primchip{cuboid})
  \\primchipn{<key>}{<n>}                  square + name + count ("Cuboid x168")
  \\primkeyline                            the whole key, family by family
Keys are the texKey column (cube, cuboid, wedge, taperedbox, pyramid, sphere, ...). The script also checks that the
families sit in separate CIE L* bands (greyscale) and prints the table.
Run: python3 tools/report/gen_prim_colors.py"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HDR = os.path.join(ROOT, "src", "report", "PrimitiveColors.h")
OUT = os.path.join(ROOT, "report", "prim_colors.tex")

ROW = re.compile(r'\{"([^"]+)", "([a-z]+)", "([^"]+)", "([a-z]+)", (\d+), (\d+), (\d+), ([\d.]+)\}')


def load():
    rows = []
    for m in ROW.finditer(open(HDR).read()):
        key, tk, label, fam, r, g, b, _ = m.groups()
        rows.append(dict(key=key, tex=tk, label=label, family=fam, rgb=(int(r), int(g), int(b))))
    if len(rows) != 16:
        sys.exit("expected 16 colours in %s, found %d" % (HDR, len(rows)))
    return rows


def lstar(rgb):
    def lin(v):
        s = v / 255.0
        return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4
    y = 0.2126 * lin(rgb[0]) + 0.7152 * lin(rgb[1]) + 0.0722 * lin(rgb[2])
    return 116 * y ** (1 / 3) - 16 if y > 0.008856 else 903.3 * y


def main():
    rows = load()
    bands = {}
    for r in rows:
        r["L"] = lstar(r["rgb"])
        lo, hi = bands.get(r["family"], (999, -999))
        bands[r["family"]] = (min(lo, r["L"]), max(hi, r["L"]))
    order = sorted(bands.items(), key=lambda kv: kv[1][0])
    for (fa, (lo_a, hi_a)), (fb, (lo_b, hi_b)) in zip(order, order[1:]):
        if lo_b - hi_a < 2.5:
            sys.exit("families %s (L* %.1f-%.1f) and %s (L* %.1f-%.1f) overlap in greyscale" % (fa, lo_a, hi_a, fb, lo_b, hi_b))
    for fa, (lo, hi) in order:
        print("%-9s L* %5.1f - %5.1f" % (fa, lo, hi))
    o = ["% generated by tools/report/gen_prim_colors.py from src/report/PrimitiveColors.h: do not edit"]
    for r in rows:
        o.append("\\definecolor{prim-%s}{RGB}{%d,%d,%d}" % ((r["tex"],) + r["rgb"]))
        o.append("\\expandafter\\def\\csname primlabel@%s\\endcsname{%s}" % (r["tex"], r["label"]))
    o.append(r"\newcommand{\primsq}[1]{\textcolor{black!70}{\fboxsep=0pt\fboxrule=0.3pt\fbox{\textcolor{prim-#1}{\rule{0.62em}{0.62em}}}}}")
    o.append(r"\newcommand{\primchip}[1]{\mbox{\primsq{#1}\,\csname primlabel@#1\endcsname}}")
    o.append(r"\newcommand{\primchipn}[2]{\mbox{\primsq{#1}\,\csname primlabel@#1\endcsname\,$\times$#2}}")
    fams = []
    for r in rows:
        if r["family"] not in fams:
            fams.append(r["family"])
    parts = []
    for fa in fams:
        parts.append("\\textit{%s:}~%s" % (fa, "~".join("\\primchip{%s}" % r["tex"] for r in rows if r["family"] == fa)))
    o.append("\\newcommand{\\primkeyline}{%s}" % "\\quad ".join(parts))
    # Map export names -> tex keys for the generators (as a comment, read by tools/report/primkey.py)
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
