chapter("trs", "Transformations and the scene graph")
plate("Every generator makes its shape one unit big, at the origin. A part becomes a real thing through one matrix: "
      "scale it, rotate it, then move it. The order matters. Scale, rotate, translate puts a drone arm where it "
      "belongs. Translate first and then rotate, and the arm swings away round the origin.", "trs", title="M = T R S, and why the order matters")
plate("Parts hang on each other. A rotor blade is placed relative to its hub. The hub is placed relative to the arm, "
      "the arm relative to the body. The world matrix of the blade is the product of all of them, parent first. Turn "
      "the hub, and the blade follows without any extra code.", "graph", title="The scene graph: parent times child")
take("graph", 16.5, "3 8.6 16 0 7.5 12.5 40")
live("The H key draws the local axes of the nodes. On a drone you can see the frames inside each other: the body, "
     "and inside it the two frames of the camera mount.",
     [(0, "set flare 0"), (0, "track uav UAV-1 1.9 0.75 9 30 40 cut"), (1.0, "set axes 1", "H")], title="H: the axes of the nodes")
live("The radar turns on its own frame. The dish tilts inside the frame that turns.",
     [(0, "orbit 29 4.5 -3 11 5 8 200 50 cut")], title="A hierarchy in motion", min=6.5)
live("A soldier is the deepest one: seventy-five parts, seven levels. Hip, thigh, shin, foot. When he walks, only "
     "the joint angles change.",
     [(0, "track soldier PATROL 3.4 1.5 14 30 45 cut"), (0.1, "axes soldier PATROL"), ("100%-0.4", "axes off")], title="A soldier: 75 parts, 7 levels", min=9.0)
card("What was compared: moving every part by itself, or a hierarchy. Chosen: a hierarchy, so that one angle on a "
     "parent moves everything below it.", "Decision",
     ["compared   each part alone  /  a hierarchy", "chosen     scene graph, world = parent x local",
      "why        one angle moves a whole limb, turret or rotor"])
