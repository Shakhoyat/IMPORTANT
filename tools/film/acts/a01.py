# ------------------------------------------------------------------------------------------------------- act 1
act("Geometry")
chapter("prims", "From a triangle to sixteen primitives")
card("Question one. A graphics card can only draw triangles. How do you get a tank out of triangles, without a "
     "modelling program?", "1  Geometry", ["How do you build a tank", "from triangles, in code?"], kind="act")
plate("Start with one triangle: three corners, each with a position and a normal. Two triangles make a square face. "
      "Six faces make a cube. A face shares its corners between its two triangles, so the cube stores twenty-four "
      "corners and thirty-six indices instead of thirty-six full corners.", "triangle", title="Vertices, indices, triangles")
plate("A curved shape is the same idea with more pieces. A sphere is cut into slices and stacks. With eight slices it "
      "is a rough ball. With thirty-six slices and eighteen stacks it has six hundred and fourteen corners and one "
      "thousand two hundred and twenty-four triangles, and it looks round. The counts come from two short formulas.",
      "sphere", title="Tessellation: how round is round enough")
plate("The program has sixteen such generators, and nothing else. Box shapes: cube, cuboid, wedge, tapered box, "
      "pyramid. Round shapes: sphere, hemisphere, capsule. Shapes turned about an axis: cylinder, frustum, cone. Rings: "
      "torus, annulus, helix. And two special ones: a blade of grass and the ground.", "primgrid", title="The sixteen primitives")
take("prims", 16.5, "-22 15 34 0 0.5 2 55")
live("In the program, the F key recolours every part by the generator that made it. Blue is a box. Green is a "
     "cylinder. Orange is a sphere. The whole camp is five thousand four hundred and seventy-four parts, and each one "
     "is one of the sixteen.",
     [(0, "orbit 0 0.5 2 40 17 5 125 55 cut"), (1.6, "set view prims", "F")], title="F: which primitive made each part")
live("The G key pulls every object apart into its parts, and puts it back.",
     [(0.6, "set explode 1", "G"), ("100%-1.6", "set explode 0", "G")], title="G: explode into parts", min=7.0)
live("And X shows the triangles themselves: first with hidden lines removed, then as an x-ray.",
     [(0.3, "set view visible"), (0.6, "set edges hidden", "X"), ("55%", "set edges xray", "X"), ("100%-0.5", "set edges solid")],
     title="X: wireframe", min=8.0)
