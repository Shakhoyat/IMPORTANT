"""v10 report numbers: every number the LaTeX text quotes comes from here (no hand-typed measurements).
Inputs: `ts --export-docs` JSON, build/test_results.json, report/data/bench.csv (if present), report/figures/plots/plot_facts.json.
Writes report/sections/gen_numbers.tex (macros) and report/sections/gen_tables.tex (primitive / object tables).
Run: python3 tools/v10/gen_numbers.py EXPORT.json"""
import csv
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SEC = os.path.join(ROOT, "report", "sections")
exp = json.load(open(sys.argv[1]))
tests = json.load(open(os.path.join(ROOT, "build", "test_results.json")))
m = {}


def num(v, fmt="{:,}"):
    return fmt.format(v).replace(",", "{,}")


m["nLeaves"] = num(exp["leaf_count"])
m["nObjects"] = str(len(exp["objects"]))
m["nTests"] = str(len(tests))
m["nPass"] = str(sum(1 for t in tests if t["status"] == "PASS"))
m["nControllables"] = str(len(exp["controllables"]))
prims = {p["type"]: p for p in exp["primitives"]}
inst = sum(p["instances"] for p in exp["primitives"])
m["nInstances"] = num(inst)
L = exp["lights"]
m["spotInner"] = f'{L["spot"]["inner_deg"]:g}'
m["spotOuter"] = f'{L["spot"]["outer_deg"]:g}'
m["spotLin"] = f'{L["spot"]["linear"]:g}'
m["spotQuad"] = f'{L["spot"]["quadratic"]:g}'
m["beaconLin"] = f'{L["beacon"]["linear"]:g}'
m["beaconQuad"] = f'{L["beacon"]["quadratic"]:g}'
m["moonI"] = f'{L["moon"]["intensity"]:g}'
facts = os.path.join(ROOT, "report", "figures", "plots", "plot_facts.json")
if os.path.exists(facts):
    f = json.load(open(facts))
    m["daySeconds"] = f'{f["day_seconds"]:.1f}'
    m["dayMinutes"] = f'{f["day_seconds"] / 60:.1f}'
bench = os.path.join(ROOT, "report", "data", "bench.csv")
rows = list(csv.DictReader(open(bench))) if os.path.exists(bench) else []

with open(os.path.join(SEC, "gen_numbers.tex"), "w") as o:
    o.write("% generated by tools/v10/gen_numbers.py: do not edit\n")
    for k, v in m.items():
        o.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

with open(os.path.join(SEC, "gen_tables.tex"), "w") as o:
    o.write("% generated by tools/v10/gen_numbers.py: do not edit\n")
    # primitive table: the 16 primitives of the library (export "primitives", report order P01..P16)
    o.write("\\newcommand{\\primtable}{\\begin{tabular}{@{}rllrrllr@{}}\\toprule\n")
    o.write("\\# & Primitive & Generator call & $V$ & $T$ & $V$ formula & $T$ formula & Instances\\\\\\midrule\n")
    def fx(f):
        f = f.split("=", 1)[1].strip() if "=" in f else f
        f = f.replace("(D = triangles dropped inside the entrance trench)", "").strip()
        return "$" + f.replace(" x ", "\\times ").replace("faces", "\\text{ faces}").replace("corners", "\\text{ corners}") \
            .replace("quads", "\\text{ quads}").replace("triangles", "\\text{ tri}").replace("sides", "\\text{ sides}") \
            .replace("rows", "\\text{ rows}").replace("segments", "\\text{ seg.}").replace("tip", "\\text{tip}") \
            .replace("(the cube mesh)", "") + "$"
    for p in exp["primitives"]:
        fn = p["function"].replace("_", "\\_")
        if p["name"] == "cuboid":
            fn = "createCube(), $S$ non-uniform"
        ins = num(p["instances"]) if p["instances"] or not p.get("gpu_instances") else f'({num(p["gpu_instances"])} GPU)'
        o.write(f'{p["number"]} & \\primsq{{{p["name"].replace(" ", "")}}}~{p["name"]} & \\code{{{fn}}} & {num(p["vertices"])} & {num(p["triangles"])} & '
                f'{fx(p["formula_V"])} & {fx(p["formula_T"])} & {ins}\\\\\n')
    o.write(f"\\midrule\\multicolumn{{7}}{{@{{}}l}}{{Primitive instances in the scene (parts)}} & {num(inst)}\\\\\\bottomrule\\end{{tabular}}}}\n")
    # object table, per unit: one row per object kind with an explicit instance count (x n). Units are the root
    # subtrees of the export's components (the export's "Autonomous UAV" holds two UAVs, "Target Rover" six rovers;
    # tanks and soldiers are separate objects of the same design).
    import collections, re
    comps = exp["components"]
    by_obj = collections.defaultdict(list)
    for c in comps:
        by_obj[c["object"]].append(c)
    units = []  # (kind, unit signature dict)
    for ob in exp["objects"]:
        cs = by_obj[ob["object"]]
        ids = {c["id"]: c for c in cs}
        kids = collections.defaultdict(list)
        for c in cs:
            kids[c["parent_id"]].append(c["id"])
        for root in [c for c in cs if c["parent_id"] not in ids]:
            stack, sub = [root["id"]], []
            while stack:
                i = stack.pop()
                sub.append(ids[i])
                stack += kids[i]
            leaves = [c for c in sub if c["primitive"] != "Group"]
            def pname(c):
                if c["primitive"] == "Cube":
                    sc = c.get("S_rest", c["S"])
                    return "Cuboid" if max(sc) - min(sc) > 1e-4 * max(1e-6, max(sc)) else "Cube"
                return c["primitive"]
            prim = collections.Counter(pname(c) for c in leaves)
            sig = dict(parts=len(leaves), groups=len(sub) - len(leaves), anim=sum(1 for c in sub if c.get("animation")),
                       prim=prim)
            units.append((re.sub(r"\s+\d+$", "", ob["object"]), sig))
    kinds = collections.OrderedDict()
    for kind, sig in units:
        kinds.setdefault(kind, []).append(sig)
    prim_cols = []
    for p_ in exp["primitives"]:
        t = p_["type"]
        if t != "Terrain disc" and any(sig["prim"].get(t) for _, sig in units):
            prim_cols.append(t)
    short = {"Cylinder (frustum)": "Frustum", "Tapered box": "Tap.\\,box", "Hemisphere": "Hemisph."}
    o.write("\\newcommand{\\objtable}{\\begin{tabular}{@{}lr" + "r" * 3 + "r" * len(prim_cols) + "@{}}\\toprule\n")
    o.write("Object (per unit) & $\\times n$ & Parts & Groups & Anim. & " +
            " & ".join("\\rotatebox{90}{" + short.get(t, t) + "}" for t in prim_cols) + "\\\\\\midrule\n")
    total_parts = 0
    for kind, sigs in kinds.items():
        s0 = sigs[0]
        same = all(x == s0 for x in sigs)
        total_parts += sum(x["parts"] for x in sigs)
        if kind == "Terrain":
            cells = ["--"] * len(prim_cols)
        else:
            cells = [str(s0["prim"].get(t, 0)) for t in prim_cols]
        flag = "" if same else "$^\\ast$"
        o.write(f"{kind}{flag} & {len(sigs)} & {s0['parts']} & {s0['groups']} & {s0['anim']} & " + " & ".join(cells) + "\\\\\n")
    o.write("\\midrule\\multicolumn{2}{@{}l}{Scene total (all units)} & " + str(total_parts) + " & \\multicolumn{" +
            str(2 + len(prim_cols)) + "}{l}{}\\\\\\bottomrule\\end{tabular}}\n")
    rank = sorted(exp["objects"], key=lambda ob: -ob["parts"])
    pos = [i for i, ob in enumerate(rank) if ob["object"] == "Command Bunker"][0]
    words = ["largest", "second-largest", "third-largest", "fourth-largest", "fifth-largest", "sixth-largest"]
    parts_of = {ob["object"]: ob["parts"] for ob in exp["objects"]}
    o.write(f"\\newcommand{{\\bunkerParts}}{{{parts_of['Command Bunker']}}}\n\\newcommand{{\\bunkerRank}}{{{words[pos]}}}\n")
    o.write("\\newcommand{\\bunkerAbove}{" + ", ".join(ob["object"] for ob in rank[:pos]) + "}\n")
    for kind, tag in [("Target Rover", "rover"), ("Autonomous UAV", "uav"), ("Main Battle Tank", "tank"), ("Soldier", "soldier")]:
        sg = kinds[kind]
        o.write(f"\\newcommand{{\\{tag}N}}{{{len(sg)}}}\\newcommand{{\\{tag}Parts}}{{{sg[0]['parts']}}}"
                f"\\newcommand{{\\{tag}Anim}}{{{sg[0]['anim']}}}\n")
    for key, macro in [("Base", "partsBase"), ("Environment", "partsEnv"), ("Camp camouflage", "partsCamp")]:
        o.write(f"\\newcommand{{\\{macro}}}{{{num(parts_of[key])}}}\n")
    # benchmark table
    o.write("\\newcommand{\\benchtable}{")
    if rows:
        o.write("\\begin{tabular}{@{}lrrrrr@{}}\\toprule Configuration & mean ms & p95 ms & fps & draws & triangles\\\\\\midrule\n")
        for r in rows:
            o.write(f'{r["config"]} & {float(r["avg_ms"]):.2f} & {float(r["p95_ms"]):.2f} & {float(r["avg_fps"]):.1f} & '
                    f'{float(r["draw_calls"]):.0f} & {num(int(float(r["triangles"])))}\\\\\n')
        o.write("\\bottomrule\\end{tabular}")
    else:
        o.write("\\todo{benchmark not run yet (report/data/bench.csv missing)}")
    o.write("}\n")
# short analysis of the benchmark, every number taken from the CSV
by = {r["config"]: r for r in rows}
def ms(name):
    return float(by[name]["avg_ms"]) if name in by else None
lines = []
bj = os.path.join(ROOT, "report", "data", "bench.json")
ph = {p["name"]: p for p in json.load(open(bj))["phases"]} if os.path.exists(bj) else {}
def spread(name):
    r = ph.get(name, {}).get("frame_ms_rounds", [])
    return (max(r) - min(r)) if r else None
if rows:
    d, n = ms("EPIC day 10:30"), ms("EPIC night 23:00 (game: waves, UAVs)")
    sp = [spread(r["config"]) for r in rows if spread(r["config"]) is not None]
    if sp:
        lines.append(f"Between the three rounds of one configuration the frame time varies by {min(sp):.1f}--{max(sp):.1f}\\,ms, "
                     "so differences of a few milliseconds are not significant.")
    if d and n:
        lines.append(f"The night configuration (searchlights, beams, lamps, intruders, both UAV cameras rendering) costs "
                     f"{n - d:+.2f}\\,ms over day ({d:.2f} to {n:.2f}\\,ms).")
    t = ms("EPIC day, thermal view")
    if d and t and ph:
        lines.append(f"The thermal view frame is {d - t:.2f}\\,ms shorter and draws "
                     f"{ph['EPIC day, thermal view']['avg_triangles_main'] / 1e6:.1f}\\,M triangles against "
                     f"{ph['EPIC day 10:30']['avg_triangles_main'] / 1e6:.1f}\\,M in the visible view.")
    sh = ms("EPIC day, shadows off")
    if d and sh:
        lines.append(f"Turning shadows off changes the day frame by {sh - d:+.2f}\\,ms, within that variation.")
    ni = ms("EPIC day, non-indexed")
    if d and ni:
        lines.append(f"Non-indexed drawing is the one large effect: {ni - d:+.2f}\\,ms ({float(by['EPIC day, non-indexed']['avg_fps']):.1f}\\,fps), "
                     "with non-indexed meshes every triangle stores its own three vertices instead of sharing them (a sphere: 3672 vertices instead of 614, Table~\\ref{tab:prims}).")
    ladder = [(q, ms(q + " day")) for q in ("LOW", "HIGH", "ULTRA")] + [("EPIC", d)]
    if all(v for _, v in ladder):
        lines.append("Quality presets: " + ", ".join(f"{q} {v:.2f}\\,ms" for q, v in ladder) +
                     " (ULTRA uses 8$\\times$ MSAA, EPIC 4$\\times$ plus TAA).")
    e = ph.get("EPIC day 10:30")
    if e:
        lines.append(f"In this headless setup much of a frame is CPU time: {e['cpu_step_ms']:.2f}\\,ms simulation and UAV camera "
                     f"submission plus {e['cpu_render_ms']:.2f}\\,ms rendering, of which {e['cpu_uav_vision_ms']:.2f}\\,ms is the "
                     "UAV images' sensor model and CV (synchronous in the benchmark; on a worker thread in the game).")
    best = min(rows, key=lambda r: float(r["avg_ms"]))
    worst = max(rows, key=lambda r: float(r["p95_ms"]))
    lines.append(f"Fastest: {best['config']} at {float(best['avg_fps']):.1f}\\,fps; worst 95th percentile: "
                 f"{float(worst['p95_ms']):.2f}\\,ms ({worst['config']}). Every configuration except non-indexed drawing "
                 "averages at least 60\\,fps." if all(float(r['avg_fps']) >= 60 for r in rows if 'non-indexed' not in r['config'])
                 else f"Fastest: {best['config']} at {float(best['avg_fps']):.1f}\\,fps.")
open(os.path.join(SEC, "gen_bench_text.tex"), "w").write(
    "% generated by tools/v10/gen_numbers.py\n" + ("\\textbf{Analysis.} " + " ".join(lines) if lines else "\\todo{benchmark analysis: no CSV}") + "\n")
rt = os.path.join(ROOT, "report", "figures", "raw", "rt", "raytrace_perf.json")
with open(os.path.join(SEC, "gen_tables.tex"), "a") as o:
    o.write("\\newcommand{\\rtperftable}{")
    if os.path.exists(rt):
        j = json.load(open(rt))
        o.write("\\begin{tabular}{@{}lrrl@{}}\\toprule Mode & ms / frame & ray pass ms & internal size\\\\\\midrule\n")
        for md in j["modes"]:
            iw, ih = md["internal"]
            o.write(f'{md["mode"].title().replace(" Rt", " RT")} & {md["ms_per_frame"]:.2f} & {md["rt_pass_ms"]:.2f} & '
                    f'{(str(iw) + "$\\times$" + str(ih)) if iw else "--"}\\\\\n')
        o.write(f'\\bottomrule\\end{{tabular}}}}\n\\newcommand{{\\rtperfsize}}{{{j["size"][0]}$\\times${j["size"][1]}}}\n')
    else:
        o.write("\\todo{raytrace\\_perf.json not captured yet}}\n\\newcommand{\\rtperfsize}{--}\n")
print("wrote", len(m), "macros;", len(rows), "benchmark rows")
