def slug(t):
    o = ""
    for ch in t:
        if ch.isalnum():
            o += ch.lower()
        elif o and o[-1] != "_":
            o += "_"
    return o.rstrip("_")


def jlist(path):
    j = json.load(open(path))
    if isinstance(j, list):
        return j
    return next(v for v in j.values() if isinstance(v, list))


def grid(items, per_row, width):
    cells, rows_ = [], []
    for k, (img, lab) in enumerate(items):
        cells.append(f"\\begin{{tabular}}[t]{{@{{}}c@{{}}}}\\raw{{{img}}}{{{width}}}\\\\[-0.5mm]"
                     f"\\parbox[t]{{{width}}}{{\\centering\\fontsize{{7}}{{8}}\\selectfont {lab}}}\\end{{tabular}}")
        if k == len(items) - 1 and len(cells) < per_row:  # pad the last row so it keeps the grid's column positions
            cells += [f"\\begin{{tabular}}[t]{{@{{}}c@{{}}}}\\rule{{{width}}}{{0pt}}\\end{{tabular}}"] * (per_row - len(cells))
        if len(cells) == per_row or k == len(items) - 1:
            rows_.append("".join(c + "\\hfill" for c in cells[:-1]) + cells[-1] + ("\\hfill" * 0))
            cells = []
    return "\\\\[1mm]\n".join("\\noindent " + r + ("" if i < len(rows_) - 1 or True else "") for i, r in enumerate(rows_))


