def proj(p):  # oblique view: x right, y up, z towards the viewer (down-left)
    x, y, z = p
    return (x - 0.42 * z, y - 0.30 * z)


for key in ("cube", "wedge", "tapered box", "pyramid"):
    p = PR[key]
    cs, fs = p["corners"], p["faces"]
    name = "".join(w.title() for w in key.split())
    lines = [f"v_{{{i}}} & {f(c[0])} & {f(c[1])} & {f(c[2])}\\\\" for i, c in enumerate(cs)]
    out.append(f"\\newcommand{{\\corners{name}}}{{\\begin{{tabular}}{{@{{}}lrrr@{{}}}}\\toprule & $x$ & $y$ & $z$\\\\\\midrule")
    out += [("$" + l.split(" & ", 1)[0] + "$ & " + l.split(" & ", 1)[1]) for l in lines]
    out.append("\\midrule\\multicolumn{4}{@{}p{2.9cm}@{}}{\\raggedright faces: " + ", ".join("(" + " ".join(str(i) for i in fc) + ")" for fc in fs) +
               "}\\\\\\bottomrule\\end{tabular}}")
    # visibility of a face for the drawing: outward normal towards the viewer direction (0.42, 0.30, 1)
    view = np.array([0.42, 0.30, 1.0])
    edges = {}
    for fc in fs:
        P = [np.array(cs[i]) for i in fc]
        n = np.cross(P[1] - P[0], P[2] - P[0])
        if np.dot(n, P[0]) < 0:
            n = -n  # outward (the shapes are convex and contain the origin)
        vis = np.dot(n, view) > 1e-6
        for k in range(len(fc)):
            e = tuple(sorted((fc[k], fc[(k + 1) % len(fc)])))
            edges[e] = edges.get(e, False) or vis
    tk = ["\\begin{tikzpicture}[scale=2.3,font=\\scriptsize]"]
    for (a, b), vis in sorted(edges.items(), key=lambda kv: kv[1]):
        pa, pb = proj(cs[a]), proj(cs[b])
        st = "thick,black!80" if vis else "dashed,black!45"
        tk.append(f"\\draw[{st}] ({pa[0]:.3f},{pa[1]:.3f}) -- ({pb[0]:.3f},{pb[1]:.3f});")
    ctr = np.mean([proj(c) for c in cs], axis=0)
    for i, c in enumerate(cs):
        q = np.array(proj(c))
        dvec = q - ctr
        dvec = dvec / (np.linalg.norm(dvec) + 1e-9) * 0.13
        tk.append(f"\\fill ({q[0]:.3f},{q[1]:.3f}) circle (0.022);")
        tk.append(f"\\node[fill=white,inner sep=0.6pt] at ({q[0] + dvec[0]:.3f},{q[1] + dvec[1]:.3f}) {{$v_{{{i}}}$}};")
    tk.append("\\draw[-latex,red!70!black] (0,0) -- (0.32,0) node[right=-1pt] {$x$};")
    tk.append("\\draw[-latex,green!45!black] (0,0) -- (0,0.32) node[above=-1pt] {$y$};")
    tk.append("\\draw[-latex,blue!70!black] (0,0) -- (-0.134,-0.096) node[below left=-2pt] {$z$};")
    tk.append("\\end{tikzpicture}")
    out.append(f"\\newcommand{{\\cornerfig{name}}}{{" + "\n".join(tk) + "}")

