"""v10: parts tables for the decomposition catalogue (report/sections/gen_decomp.tex). Source: ts --export-docs.
\\decomp<Object>: every part of one unit, grouped by (primitive, material): count, the base colour and specular /
  shininess of the group's first part, and the part kinds in it. Cube parts with a non-uniform scale are cuboids.
\\mainparts<Object>: the largest parts of one unit (by the volume of their rest scale S) with S, T, R and parent.
Run: python3 tools/v10/gen_decomp.py EXPORT.json"""
import collections
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
d = json.load(open(sys.argv[1]))
OBJECTS = ["Autonomous UAV", "Soldier 1", "Main Battle Tank", "Scout Helicopter", "Target Rover", "AA Gatling Gun",
           "SAM launcher", "MLRS rocket truck", "Air-defence radar", "Command Bunker", "Barracks hall", "Ammunition bunker",
           "Flag", "Windsock", "Boom barrier", "UAV pads"]
MAIN = {"Autonomous UAV": 12, "Soldier 1": 12, "Main Battle Tank": 12, "Command Bunker": 12}


def tex(s):
    return s.replace("&", "\\&").replace("_", "\\_").replace("#", "\\#").replace("%", "\\%")


def prim_name(c):
    p = c["primitive"].replace("Cylinder (frustum)", "Frustum")
    if p == "Cube":
        s = c.get("S_rest", c["S"])
        if max(s) - min(s) > 1e-4 * max(1e-6, max(s)):
            return "Cuboid"
    return p


def kind(name):
    return re.sub(r"(\s+(L|R|left|right|front|rear|\d+|[A-Z]))+$", "", name).strip()


def unit_parts(obj):
    allc = [c for c in d["components"] if c["object"] == obj]
    ids = {c["id"]: c for c in allc}
    kids = collections.defaultdict(list)
    for c in allc:
        kids[c["parent_id"]].append(c["id"])
    root = [c for c in allc if c["parent_id"] not in ids][0]
    stack, sub = [root["id"]], []
    while stack:
        i = stack.pop()
        sub.append(ids[i])
        stack += kids[i][::-1]
    return [c for c in sub if c["primitive"] != "Group"], ids


def swatch(c):
    r, g, b = c["color"]
    return f"\\textcolor[rgb]{{{min(r,1):.3f},{min(g,1):.3f},{min(b,1):.3f}}}{{\\rule{{2.2mm}}{{2.2mm}}}}"


def fmt3(v, k=100, dec=1, sep="$\\times$"):
    def one(x):
        y = k * x
        return f"{y:.0f}" if abs(y) >= 10 or dec == 0 else f"{y:.{dec}f}".rstrip("0").rstrip(".")
    return sep.join(one(x) for x in v)


out = ["% generated by tools/v10/gen_decomp.py: do not edit"]
for obj in OBJECTS:
    parts, ids = unit_parts(obj)
    if not parts:
        continue
    name = "decomp" + "".join(ch for ch in obj.title() if ch.isalpha())
    groups = collections.OrderedDict()
    for c in parts:
        groups.setdefault((prim_name(c), c.get("surface", "")), []).append(c)
    ranked = sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0]))
    rows = []
    for (pr, mat), cs in ranked:
        kinds = collections.Counter(kind(c["name"]) for c in cs)
        names = [k for k, _ in kinds.most_common()]
        shown = ", ".join(tex(k) for k in names[:2]) + (f" +{len(names) - 2}" if len(names) > 2 else "")
        c = cs[0]
        rows.append(f"{pr} & {tex(mat)} & {len(cs)} & {swatch(c)} & {c['specular']:.2f} / {c['shininess']:.0f} & {shown}\\\\")
    hid = [c for c in parts if c.get("hidden_at_export")]
    prim_tot = collections.Counter(prim_name(c) for c in parts)
    tot = ", ".join(f"{k} {v}" for k, v in sorted(prim_tot.items()))
    out.append(f"\\newcommand{{\\{name}}}{{\\begin{{tabular}}{{@{{}}llrcl>{{\\raggedright\\arraybackslash}}p{{3.1cm}}@{{}}}}\\toprule")
    out.append("Primitive & Material & n & RGB & $k_s$ / $n$ & Part kinds\\\\\\midrule")
    out += rows
    foot = f"\\textbf{{{len(parts)} parts:}} {tot}"
    if hid:
        foot += f"; {len(hid)} hidden at export (shown at rest scale)"
    out.append(f"\\midrule\\multicolumn{{6}}{{@{{}}l}}{{{foot}}}\\\\\\bottomrule\\end{{tabular}}}}")
    out.append(f"\\newcommand{{\\{name}N}}{{{len(parts)}}}\\newcommand{{\\{name}G}}{{{len(ranked)}}}")
    if obj in MAIN:
        def vol(c):
            s = c.get("S_rest", c["S"])
            return abs(s[0] * s[1] * s[2])
        seen, top = set(), []
        for c in sorted(parts, key=lambda c: -vol(c)):
            if kind(c["name"]) not in seen:
                seen.add(kind(c["name"]))
                top.append(c)
        top = top[:MAIN[obj]]
        top.sort(key=lambda c: c.get("dfs_index", 0))
        mrows = []
        for c in top:
            par = ids.get(c["parent_id"])
            pn = tex(par["name"]) if par else "--"
            mrows.append(f"{tex(c['name'])} & {prim_name(c)} & {fmt3(c.get('S_rest', c['S']))} & ({fmt3(c['T'], sep=', ')}) & "
                         f"({fmt3(c['R_deg'], 1, 0, sep=', ')}) & {pn}\\\\")
        out.append(f"\\newcommand{{\\main{name[6:]}}}{{\\begin{{tabular}}{{@{{}}llllll@{{}}}}\\toprule")
        out.append("Part & Primitive & $S$ (cm) & $T$ (cm) & $R$ ($^\\circ$) & Parent\\\\\\midrule")
        out += mrows
        out.append("\\bottomrule\\end{tabular}}")
open(os.path.join(ROOT, "report", "sections", "gen_decomp.tex"), "w").write("\n".join(out) + "\n")
print("objects:", len(OBJECTS))
