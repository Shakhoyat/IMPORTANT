"""v10: one compact parts table per major object for the decomposition catalogue (report/sections/gen_decomp.tex).
Rows group the parts of one object by (part name, primitive); dimensions are the local scale S (metres) of the first
part of each group, colour is its base RGB (a swatch), material is specular / shininess. Source: ts --export-docs.
Run: python3 tools/v10/gen_decomp.py EXPORT.json"""
import collections
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
d = json.load(open(sys.argv[1]))
OBJECTS = ["Autonomous UAV", "Soldier 1", "Main Battle Tank", "Scout Helicopter", "Target Rover", "AA Gatling Gun",
           "SAM launcher", "MLRS rocket truck", "Air-defence radar", "Command Bunker", "Barracks hall", "Ammunition bunker",
           "Flag", "Windsock", "Boom barrier", "UAV pads"]
ROWS = 9


def tex(s):
    return s.replace("&", "\\&").replace("_", "\\_").replace("#", "\\#").replace("%", "\\%")


out = ["% generated by tools/v10/gen_decomp.py: do not edit"]
macro_names = {}
for obj in OBJECTS:
    allc = [c for c in d["components"] if c["object"] == obj]
    if not allc:
        continue
    # one unit: the first root subtree (the export's "Autonomous UAV" holds 2 UAVs, "Target Rover" 6 rovers)
    ids = {c["id"]: c for c in allc}
    kids = collections.defaultdict(list)
    for c in allc:
        kids[c["parent_id"]].append(c["id"])
    root = [c for c in allc if c["parent_id"] not in ids][0]
    stack, sub = [root["id"]], []
    while stack:
        i = stack.pop()
        sub.append(ids[i])
        stack += kids[i]
    parts = [c for c in sub if c["primitive"] != "Group"]
    groups = collections.OrderedDict()
    for c in parts:
        groups.setdefault((c["name"], c["primitive"]), []).append(c)
    ranked = sorted(groups.items(), key=lambda kv: -len(kv[1]))
    prim_tot = collections.Counter(c["primitive"] for c in parts)
    name = "decomp" + "".join(ch for ch in obj.title() if ch.isalpha())
    macro_names[obj] = name
    rows = []
    for (pn, pr), cs in ranked[:ROWS]:
        c = cs[0]
        s = c.get("S_rest", c["S"])
        hidden = max(s) < 1e-3  # zero-scaled at export time (e.g. shell casings until a burst ejects them)
        r, g, b = c["color"]
        sw = f"\\textcolor[rgb]{{{min(r,1):.3f},{min(g,1):.3f},{min(b,1):.3f}}}{{\\rule{{2.2mm}}{{2.2mm}}}}"
        rows.append(f"{tex(pn)} & {pr.replace('Cylinder (frustum)', 'Frustum')} & {len(cs)} & "
                    + (f"{100*s[0]:.1f}$\\times${100*s[1]:.1f}$\\times${100*s[2]:.1f}" if not hidden else "hidden$^\\dagger$") + f" & {sw} & {c['specular']:.2f} / {c['shininess']:.0f}\\\\")
    rest = len(parts) - sum(len(cs) for _, cs in ranked[:ROWS])
    if rest > 0:
        rows.append(f"\\multicolumn{{2}}{{@{{}}l}}{{\\textit{{{len(ranked) - ROWS} more part kinds}}}} & {rest} & & & \\\\")
    hid = [c for c in parts if max(c.get("S_rest", c["S"])) < 1e-3]
    if hid:
        rows.append(f"\\multicolumn{{6}}{{@{{}}l}}{{$^\\dagger$ scale {max(hid[0]['S']):.0e} at export: invisible until fired}}\\\\")
    tot = ", ".join(f"{k.replace('Cylinder (frustum)', 'Frustum')} {v}" for k, v in sorted(prim_tot.items()))
    out.append(f"\\newcommand{{\\{name}}}{{\\begin{{tabular}}{{@{{}}llrlcl@{{}}}}\\toprule")
    out.append("Part & Primitive & n & $S$ (cm) & RGB & $k_s$ / $n$\\\\\\midrule")
    out += rows
    out.append(f"\\midrule\\multicolumn{{6}}{{@{{}}l}}{{\\textbf{{{len(parts)} parts:}} {tot}}}\\\\\\bottomrule\\end{{tabular}}}}")
open(os.path.join(ROOT, "report", "sections", "gen_decomp.tex"), "w").write("\n".join(out) + "\n")
print("tables:", macro_names)
