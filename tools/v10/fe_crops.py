"""v10 M1: legible insets of the Frame Explorer captures (the pixels are not changed: LaTeX shows a clipped viewport).
Each capture is 1280x720 with fixed panels; for each wanted panel the script finds the bounding box of its text
(bright pixels) and writes report/sections/gen_fecrops.tex with one macro per inset:
  \\fe<Name><Panel>{width}  ->  \\includegraphics[viewport=...,clip,width=width]{figures/img/lab/<file>.jpg}
and prints the printed glyph size for a given width so the report can keep insets >= 7 pt.
Run: ~/.local/bin/uv run -q --with pillow --with numpy python tools/v10/fe_crops.py"""
import os

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RAW = os.path.join(ROOT, "report", "figures", "raw", "lab")
OUT = os.path.join(ROOT, "report", "sections", "gen_fecrops.tex")
# panel search regions in pixels (x0, y0, x1, y1), top-left origin
FORMULA = (744, 612, 1266, 706)
INFO = (892, 88, 1278, 560)
KERNEL = (722, 92, 1278, 300)
WANT = {
    "explorer_stage_02_vertex": {"Formula": FORMULA, "Info": (892, 88, 1278, 330)},
    "explorer_stage_03_assembly": {"Formula": FORMULA, "Info": (892, 88, 1278, 220)},
    "explorer_stage_06_depth": {"Formula": FORMULA, "Info": (1085, 88, 1278, 270)},
    "explorer_raster_scan": {"Formula": FORMULA, "Info": (872, 88, 1278, 500)},
    "explorer_interp_affine_perspective": {"Formula": FORMULA, "Info": (893, 226, 1272, 392)},
    "explorer_interp_gouraud_phong": {"Formula": FORMULA, "Info": (893, 400, 1272, 548)},
    "explorer_stage_15_taa": {"Formula": FORMULA, "Info": (892, 88, 1278, 375)},
    "explorer_imagelab_gauss_gamma": {"Kernel": KERNEL},
    "explorer_imagelab_sobel": {"Kernel": KERNEL},
}


def tight(img, box, pad=8, thr=150):
    x0, y0, x1, y1 = box
    a = np.asarray(img.convert("L").crop(box), dtype=np.int16)
    ys, xs = np.nonzero(a > thr)
    if len(xs) == 0:
        return box
    return (max(0, x0 + xs.min() - pad), max(0, y0 + ys.min() - pad), min(img.width, x0 + xs.max() + pad),
            min(img.height, y0 + ys.max() + pad))


def macro_name(file, panel):
    base = "".join(w.title() for w in file.replace("explorer_", "").split("_") if not w.isdigit())
    return "fe" + "".join(ch for ch in base if ch.isalpha()) + panel


def main():
    lines = ["% generated by tools/v10/fe_crops.py: clipped viewports of the Frame Explorer captures (pixels unchanged)"]
    for file, panels in WANT.items():
        img = Image.open(os.path.join(RAW, file + ".png"))
        h = img.height
        for panel, box in panels.items():
            x0, y0, x1, y1 = tight(img, box)
            name = macro_name(file, panel)
            # JPEG in figures/img keeps 1280 px: 1 px = 1 bp in the viewport (72 dpi default)
            vp = f"{x0} {h - y1} {x1} {h - y0}"
            # width for >= 7.3 pt: an 11 px em must print at >= 2.57 mm (7.3 pt) -> 0.2337 mm per pixel
            w_mm = min(174.0, 0.2337 * (x1 - x0))
            lines.append(f"\\newcommand{{\\{name}}}{{\\includegraphics[viewport={vp},clip,width={w_mm:.1f}mm]{{figures/img/lab/{file}.jpg}}}}")
            print(f"{name:40s} {x1 - x0:4d}x{y1 - y0:<4d} -> {w_mm:5.1f} mm")
    open(OUT, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
