"""v10 M1: appendix "Workbook sheets": every page of the LibreOffice PDF of cg_workbook.xlsx (vector, written by
build_cg_workbook.py) on its own landscape page, trimmed to its content and scaled so that the smallest text prints at
>= 7 pt (the script checks it from the PDF's text spans and fails otherwise).
Writes report/sections/gen_wb_appendix.tex. Run: ~/.local/bin/uv run -q --with pymupdf python tools/v10/gen_wb_appendix.py"""
import os
import sys

import pymupdf

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PDF = os.path.join(ROOT, "report", "workbooks", "cg_workbook.pdf")
OUT = os.path.join(ROOT, "report", "sections", "gen_wb_appendix.tex")
SHEETS = ["Primitives", "Decomposition", "Transform_Trace", "Vertex_Groups", "View_Projection", "Clipping", "Illumination",
          "Color_Interp", "Ray_Tracing", "Thermal_Kernels", "Tracking", "Line_Follower", "Explosion", "Duty_Cycle",
          "Performance"]
W_MM, H_MM = 272.0, 172.0  # landscape: the portrait text height (277 mm) less a little; room for the caption
PT_PER_MM = 72 / 25.4
MIN_PT = 7.0


def main():
    doc = pymupdf.open(PDF)
    owner, cur = [], None
    for page in doc:
        head = page.get_text().strip()[:120]
        for name in SHEETS:
            if head.startswith(name + ":"):
                cur = name
        owner.append(cur)
    lines = ["% generated by tools/v10/gen_wb_appendix.py: do not edit",
             "\\section{Workbook sheets}\\label{app:wb}",
             "Every sheet of \\code{report/workbooks/cg\\_workbook.xlsx}, as LibreOffice prints it after recalculating every "
             "formula (vector pages; yellow cells are inputs copied from the code, white cells are formulas). The body of the "
             "report typesets the key blocks of each sheet as tables."]
    worst = 99.0
    count = {}
    for i, page in enumerate(doc):
        sizes, x0, y0, x1, y1 = [], 1e9, 1e9, 0.0, 0.0
        for b in page.get_text("dict")["blocks"]:
            for ln in b.get("lines", []):
                for s in ln["spans"]:
                    if s["text"].strip():
                        sizes.append(s["size"])
                        bx = s["bbox"]
                        x0, y0, x1, y1 = min(x0, bx[0]), min(y0, bx[1]), max(x1, bx[2]), max(y1, bx[3])
        for d in page.get_drawings():  # table borders and fills belong to the content too
            r = d["rect"]
            x0, y0, x1, y1 = min(x0, r.x0), min(y0, r.y0), max(x1, r.x1), max(y1, r.y1)
        pad = 4
        x0, y0, x1, y1 = max(0, x0 - pad), max(0, y0 - pad), min(page.rect.width, x1 + pad), min(page.rect.height, y1 + pad)
        bw, bh = x1 - x0, y1 - y0
        scale = min(W_MM * PT_PER_MM / bw, H_MM * PT_PER_MM / bh, 1.25)
        printed = min(sizes) * scale
        if printed < MIN_PT: print(f"  page {i + 1} ({owner[i]}): {printed:.3f} pt")
        worst = min(worst, printed)
        name = owner[i] or "Workbook"
        count[name] = count.get(name, 0) + 1
        trim = f"{x0:.1f} {page.rect.height - y1:.1f} {page.rect.width - x1:.1f} {y0:.1f}"
        width_mm = bw * scale / PT_PER_MM
        label = f"\\label{{app:wb-{name}}}" if count[name] == 1 else ""
        part = "" if count[name] == 1 else f", page {count[name]}"
        lines += ["\\begin{landscape}", "\\begin{figure}[p]\\centering",
                  f"\\includegraphics[page={i + 1},trim={trim},clip,width={width_mm:.1f}mm]{{workbooks/cg_workbook.pdf}}",
                  f"\\caption{{Workbook sheet \\code{{{name.replace('_', chr(92) + '_')}}}{part} (smallest text {printed:.1f}\\,pt at print size).}}{label}",
                  "\\end{figure}", "\\end{landscape}"]
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"{len(doc)} pages, smallest printed text {worst:.1f} pt -> {OUT}")
    return 0 if worst >= MIN_PT else 1


if __name__ == "__main__":
    sys.exit(main())
