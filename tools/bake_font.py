"""Bakes the HUD glyph atlas (printable ASCII, 16 columns) into src/rendering/FontAtlas.inc.

The atlas is compiled into the program, so the HUD needs no font files and no OS font API
(Windows GDI was used before; this works the same on Windows and Linux).
Font: DejaVu Sans Mono Bold (Bitstream Vera / DejaVu licence, free to embed).

    uv run --with pillow python tools/bake_font.py [path/to/DejaVuSansMono-Bold.ttf]
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST, COLS = 32, 126, 16
PIXELS = 48  # glyph height the atlas is rasterised at (HUD text is scaled from this)


def rle_zeros(data: bytes) -> list[int]:
    """0 followed by a run length (1..255) encodes that many zero bytes; other bytes are literal."""
    out, i = [], 0
    while i < len(data):
        if data[i] == 0:
            n = 1
            while i + n < len(data) and data[i + n] == 0 and n < 255:
                n += 1
            out += [0, n]
            i += n
        else:
            out.append(data[i])
            i += 1
    return out


def main() -> None:
    ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
    font = ImageFont.truetype(ttf, PIXELS)
    ascent, descent = font.getmetrics()
    cell_w = int(round(font.getlength("M"))) + 2
    cell_h = ascent + descent + 2
    rows = (LAST - FIRST + 1 + COLS - 1) // COLS
    img = Image.new("L", (cell_w * COLS, cell_h * rows), 0)
    draw = ImageDraw.Draw(img)
    for ch in range(FIRST, LAST + 1):
        i = ch - FIRST
        draw.text(((i % COLS) * cell_w + 1, (i // COLS) * cell_h + 1), chr(ch), font=font, fill=255)
    data = rle_zeros(img.tobytes())
    lines = [", ".join(str(b) for b in data[k:k + 40]) for k in range(0, len(data), 40)]
    out = Path(__file__).resolve().parent.parent / "src" / "rendering" / "FontAtlas.inc"
    out.write_text(
        "// Generated by tools/bake_font.py from DejaVu Sans Mono Bold -- do not edit.\n"
        f"constexpr int kFontCellW = {cell_w}, kFontCellH = {cell_h};\n"
        f"constexpr int kFontAtlasW = {img.width}, kFontAtlasH = {img.height};\n"
        "// Zero-run-length encoded: 0, n = n zero bytes; any other byte is literal.\n"
        f"constexpr unsigned char kFontAtlasRle[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};\n")
    print(f"{out}: {img.width}x{img.height}, cell {cell_w}x{cell_h}, {len(data)} bytes")


if __name__ == "__main__":
    main()
