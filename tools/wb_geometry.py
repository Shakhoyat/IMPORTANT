# ---- 2 Primitive Vertex Data ----------------------------------------------------------------------------
def _vertex_table(ws, top, left, name, sample, extra_hdr, extra_formula):
    section(ws, top - 1, left, f"{name}: first {len(sample['vertices'])} of {sample['total_vertices']} vertices "
                               f"(x, y, z, nx, ny, nz)")
    header(ws, top, ["#", "x", "y", "z", "nx", "ny", "nz", extra_hdr], start_col=left)
    for i, v in enumerate(sample["vertices"]):
        r = top + 1 + i
        put(ws, r, left, i)
        for k in range(6):
            put(ws, r, left + 1 + k, v[k], "0.0000", INPUT_FILL)
        put(ws, r, left + 7, extra_formula(r), "0.0000")
    return top + len(sample["vertices"])


def _index_table(ws, top, left, name, indices, n_rows=None):
    tris = [indices[i:i + 3] for i in range(0, len(indices) - len(indices) % 3, 3)]
    tris = tris[:n_rows] if n_rows else tris
    section(ws, top - 1, left, f"{name}: index buffer (EBO), {len(tris)} triangles shown")
    header(ws, top, ["Triangle", "i0", "i1", "i2"], start_col=left)
    for i, t in enumerate(tris):
        r = top + 1 + i
        put(ws, r, left, i)
        for k in range(3):
            put(ws, r, left + 1 + k, t[k], FMT_INT, INPUT_FILL)
    return top + len(tris)


def _cube_winding(ws, r, vfirst, vlast):
    """Front-facing test for one cube triangle: n0 . ((p1 - p0) x (p2 - p0)) > 0  <=>  CCW seen from outside."""
    def at(c, k):  # value of vertex column c (B..G) for the vertex index in column K/L/M of this row
        return f"INDEX(${c}${vfirst}:${c}${vlast},{k}{r}+1)"

    x0, y0, z0 = at("B", "K"), at("C", "K"), at("D", "K")
    ux, uy, uz = (f"({at(c, 'L')}-{p})" for c, p in (("B", x0), ("C", y0), ("D", z0)))
    vx, vy, vz = (f"({at(c, 'M')}-{p})" for c, p in (("B", x0), ("C", y0), ("D", z0)))
    nx, ny, nz = at("E", "K"), at("F", "K"), at("G", "K")
    dot = f"{nx}*({uy}*{vz}-{uz}*{vy})+{ny}*({uz}*{vx}-{ux}*{vz})+{nz}*({ux}*{vy}-{uy}*{vx})"
    return f'=IF({dot}>0,"CCW = front","CW = back")'


def build_vertex_data(wb, ctx):
    ws = wb[S_VERT]
    scene = ctx["scene"]
    samples = scene["mesh_samples"]
    cube = samples["Cube"]
    cube_p = next(p for p in scene["primitives"] if p["type"] == "Cube")
    title(ws, "2  Primitive Vertex Data",
          "Interleaved vertex layout (x, y, z, nx, ny, nz) = 6 floats = 24 bytes per vertex (Lab-04 sheet p2), "
          "exported directly from createCube() / createSphere() / createCylinder(). Faces, winding and the "
          "Technique 1 vs Technique 2 memory comparison (Lab-04 sheet p1) are Excel formulas over these values.",
          span=14)
    vt = 5
    section(ws, vt - 1, 1, f"Cube: all {cube['total_vertices']} unique vertices (4 per face so every face has "
                           "its own normal)")
    header(ws, vt, ["#", "x", "y", "z", "nx", "ny", "nz", "Face (from normal)"])
    vfirst = vt + 1
    for i, v in enumerate(cube["vertices"]):
        r = vfirst + i
        put(ws, r, 1, i)
        for k in range(6):
            put(ws, r, 2 + k, v[k], "0.0", INPUT_FILL)
        put(ws, r, 8, f'=IF(E{r}=1,"+X",IF(E{r}=-1,"-X",IF(F{r}=1,"+Y",IF(F{r}=-1,"-Y",IF(G{r}=1,"+Z","-Z")))))')
    vlast = vfirst + len(cube["vertices"]) - 1

    section(ws, vt - 1, 10, f"Cube: all {cube['total_indices']} indices as {cube['total_indices'] // 3} triangles")
    header(ws, vt, ["Triangle", "i0", "i1", "i2", "Face", "Winding test n0.((p1-p0)x(p2-p0))"], start_col=10)
    tris = [cube["indices"][i:i + 3] for i in range(0, len(cube["indices"]), 3)]
    ifirst = vfirst
    for i, t in enumerate(tris):
        r = ifirst + i
        put(ws, r, 10, i)
        for k in range(3):
            put(ws, r, 11 + k, t[k], FMT_INT, INPUT_FILL)
        put(ws, r, 14, f"=INDEX($H${vfirst}:$H${vlast},K{r}+1)")
        put(ws, r, 15, _cube_winding(ws, r, vfirst, vlast))
    ilast = ifirst + len(tris) - 1
    ws.conditional_formatting.add(f"O{ifirst}:O{ilast}", FormulaRule(formula=[f'LEFT(O{ifirst},3)="CCW"'],
                                                                     fill=PASS_FILL))
    ws.conditional_formatting.add(f"O{ifirst}:O{ilast}", FormulaRule(formula=[f'LEFT(O{ifirst},2)="CW"'],
                                                                     fill=FAIL_FILL))
    tech_end = _technique_block(ws, ilast + 3, 10, vfirst, vlast, ifirst, ilast, cube_p)

    top = max(vlast, tech_end) + 4
    s_end = _vertex_table(ws, top, 1, "Sphere", samples["Sphere"], "|p| (radius 0.5)",
                          lambda r: f"=SQRT(B{r}^2+C{r}^2+D{r}^2)")
    c_end = _vertex_table(ws, top, 10, "Cylinder", samples["Cylinder"], "sqrt(x^2+y^2) (radius 0.5)",
                          lambda r: f"=SQRT(K{r}^2+L{r}^2)")
    top2 = max(s_end, c_end) + 3
    _index_table(ws, top2, 1, "Sphere", samples["Sphere"]["indices"])
    _index_table(ws, top2, 10, "Cylinder", samples["Cylinder"]["indices"])
    widths(ws, [8, 9, 9, 9, 9, 9, 9, 16, 3, 10, 9, 9, 9, 12, 26, 3])
    finish(ws, vt)


def _technique_block(ws, top, left, vfirst, vlast, ifirst, ilast, cube_p):
    L, V = left, left + 5
    section(ws, top, L, "Technique 1 (separate triangles) vs Technique 2 (unique vertices + indices)")
    rows = [
        ("Lab-04 p1 example: one square face (a, b, c, d) of the cube", None, None),
        ("Vertices of one face (+X face, from the table)", f"=COUNTIF($E${vfirst}:$E${vlast},1)", FMT_INT),
        ("Triangles per face (quad = vertices - 2)", "={v1}-2", FMT_INT),
        ("Technique 1 floats: triangles x 3 corners x (x,y,z)", "={v2}*3*3", FMT_INT),
        ("Technique 2 floats: unique vertices x (x,y,z)", "={v1}*3", FMT_INT),
        ("Technique 2 indices: triangles x 3", "={v2}*3", FMT_INT),
        ("Whole cube with the real layout (x,y,z,nx,ny,nz)", None, None),
        ("Floats per vertex (columns x..nz above)", f"=COLUMNS($B${vfirst - 1}:$G${vfirst - 1})", FMT_INT),
        ("Bytes per vertex (exporter, sizeof(Vertex))", cube_p["vertex_bytes"], FMT_INT),
        ("Bytes per float", "={v8}/{v7}", FMT_INT),
        ("Index size in bytes (exporter: (indexed bytes - V x 24) / I)",
         f"=({cube_p['bytes_indexed']}-COUNT($B${vfirst}:$B${vlast})*{{v8}})/COUNT($K${ifirst}:$M${ilast})", FMT_INT),
        ("Technique 1: vertices stored (= indices)", f"=COUNT($K${ifirst}:$M${ilast})", FMT_INT),
        ("Technique 1: floats", "={v11}*{v7}", FMT_INT),
        ("Technique 1: bytes", "={v12}*{v9}", FMT_INT),
        ("Technique 2: unique vertices", f"=COUNT($B${vfirst}:$B${vlast})", FMT_INT),
        ("Technique 2: floats + indices", f"={{v14}}*{{v7}}+COUNT($K${ifirst}:$M${ilast})", FMT_INT),
        ("Technique 2: bytes (floats x 4 + indices x index size)",
         f"={{v14}}*{{v8}}+COUNT($K${ifirst}:$M${ilast})*{{v10}}", FMT_INT),
        ("Saving of Technique 2", "=1-{v16}/{v13}", FMT_PCT),
        ("Check vs exporter bytes (indexed / non-indexed)",
         f'=IF(AND({{v16}}={cube_p["bytes_indexed"]},{{v13}}={cube_p["bytes_non_indexed"]}),"match","MISMATCH")',
         None),
    ]
    cells = {}
    for i, (label, _, _) in enumerate(rows):
        cells[f"v{i}"] = f"{col(V)}{top + 1 + i}"
    for i, (label, formula, fmt) in enumerate(rows):
        r = top + 1 + i
        c = put(ws, r, L, label, font=BOLD if formula is None else None)
        ws.merge_cells(start_row=r, start_column=L, end_row=r, end_column=V - 1)
        if formula is None:
            c.fill = TOTAL_FILL
            put(ws, r, V, "", fill=TOTAL_FILL)
            continue
        value = formula.format(**cells) if isinstance(formula, str) else formula
        put(ws, r, V, value, fmt, INPUT_FILL if not isinstance(formula, str) else None)
    return top + len(rows)


# ---- 3 Object Construction ------------------------------------------------------------------------------
OBJ_HDR = ["ID", "Final object", "Primitive", "Component", "Parent ID", "Depth", "Sx", "Sy", "Sz", "Rx (deg)",
           "Ry (deg)", "Rz (deg)", "Tx", "Ty", "Tz", "Shading", "Surface", "Roughness (effective)", "Metalness",
           "Heat", "Emissive", "Occluder", "Obstacle", "Animation", "Purpose"]


def build_object_construction(wb, ctx):
    ws = wb[S_OBJ]
    comps = ctx["scene"]["components"]
    title(ws, "3  Object Construction",
          "Every scene-graph node exported by the program (tree order, grouped by final object - use the outline "
          "[+]/[-] buttons on the left to collapse an object to its root). Group nodes carry only a transform; "
          "leaf nodes draw one primitive. S, R, T are the node's LOCAL transform relative to its parent. The block "
          "on the right counts components per object with COUNTIFS.", span=16)
    h = 4
    header(ws, h, OBJ_HDR)
    first = h + 1
    for i, c in enumerate(comps):
        r = first + i
        s, rot, t = c["S"], c["R_deg"], c["T"]
        vals = [c["id"], c["object"], c["primitive"], c["name"], c.get("parent_id") or "World", c.get("depth", 0),
                *s, *rot, *t, c["shading"], c.get("surface", ""), c.get("roughness_effective", ""),
                c.get("metalness", ""), c["heat"], c["emissive"], "Yes" if c["occluder"] else "No",
                "Yes" if c.get("obstacle", False) else "No", c["animation"] or "-", c["purpose"]]
        for k, v in enumerate(vals):
            fmt = FMT_3 if 6 <= k <= 14 or 17 <= k <= 20 else None
            put(ws, r, k + 1, v, fmt)
        ws.cell(row=r, column=3).fill = prim_fill(c["primitive"])
        ws.cell(row=r, column=4).alignment = Alignment(wrap_text=True, vertical="top", indent=c.get("depth", 0))
    last = first + len(comps) - 1
    table = Table(displayName="ObjectConstruction", ref=f"A{h}:{col(len(OBJ_HDR))}{last}")
    table.tableStyleInfo = TableStyleInfo(name="TableStyleMedium2", showRowStripes=True)
    ws.add_table(table)
    nowrap(ws, first, last, 1, len(OBJ_HDR))
    _group_rows(ws, comps, first)
    ctx["obj"] = {"first": first, "last": last, "rows": {c["id"]: first + i for i, c in enumerate(comps)}}

    def rng(letter):
        return f"'{S_OBJ}'!${letter}${first}:${letter}${last}"

    ctx["obj"]["range"] = rng
    _summary(ws, wb, ctx, comps, first, last)
    widths(ws, [9, 16, 15, 24, 9, 6, 7, 7, 7, 8, 8, 8, 8, 8, 8, 10, 10, 10, 9, 7, 8, 9, 9, 30, 40])
    finish(ws, h, freeze="E5")


def _group_rows(ws, comps, first):
    start = None
    for i, c in enumerate(comps + [None]):
        is_root = c is None or c.get("depth", 0) == 0
        if is_root and start is not None and first + i - 1 >= start:
            ws.row_dimensions.group(start, first + i - 1, outline_level=1, hidden=False)
        if is_root:
            start = first + i + 1
    ws.sheet_properties.outlinePr.summaryBelow = False


def _summary(ws, wb, ctx, comps, first, last):
    objects = list(dict.fromkeys(c["object"] for c in comps))
    prims = list(dict.fromkeys(c["primitive"] for c in comps if c["primitive"] != "Group"))
    left = len(OBJ_HDR) + 2
    section(ws, 3, left, "Components per object (COUNTIFS over the table)")
    hdr = ["Object"] + prims + ["Parts (leaves)", "Group nodes"]
    header(ws, 4, hdr, start_col=left)
    o_rng, p_rng = f"$B${first}:$B${last}", f"$C${first}:$C${last}"
    for i, obj in enumerate(objects):
        r = 5 + i
        put(ws, r, left, obj, font=BOLD)
        for k, p in enumerate(prims):
            put(ws, r, left + 1 + k, f"=COUNTIFS({o_rng},${col(left)}{r},{p_rng},{col(left + 1 + k)}$4)", FMT_INT)
        a, b = col(left + 1), col(left + len(prims))
        put(ws, r, left + 1 + len(prims), f"=SUM({a}{r}:{b}{r})", FMT_INT, font=BOLD)
        put(ws, r, left + 2 + len(prims), f'=COUNTIFS({o_rng},${col(left)}{r},{p_rng},"Group")', FMT_INT)
    for k, p in enumerate(prims):
        ws.cell(row=4, column=left + 1 + k).fill = prim_fill(p, strong=True)
    t = 5 + len(objects)
    put(ws, t, left, "Total", fill=TOTAL_FILL, font=BOLD)
    for k in range(len(prims) + 2):
        c = left + 1 + k
        put(ws, t, c, f"=SUM({col(c)}5:{col(c)}{t - 1})", FMT_INT, TOTAL_FILL, BOLD)
    letter = col(left + 1 + len(prims))
    parts_cell = f"{letter}{t}"
    ctx["refs"]["parts"] = f"'{S_OBJ}'!${letter}${t}"
    define_name(wb, "TotalParts", S_OBJ, parts_cell)
    for i in range(len(hdr)):
        ws.column_dimensions[col(left + i)].width = 16 if i == 0 else 11


# ---- 6 Geometry Statistics ------------------------------------------------------------------------------
GEOM_HDR = ["ID", "Primitive", "Generator", "Unique vertices (V)", "Indices (I)", "Triangles = I/3", "Instances",
            "Bytes per vertex", "Memory non-indexed = I x 24 B", "Memory indexed = V x 24 + I x 4 B",
            "Saving", "Vertex reuse = I / V", "Triangles per frame = tris x instances", "Exporter: indexed bytes",
            "Exporter: non-indexed bytes", "Formula vs exporter"]


def build_geometry(wb, ctx):
    ws = wb[S_GEOM]
    prims = ctx["scene"]["primitives"]
    title(ws, "6  Geometry Statistics",
          "Memory of every GPU mesh with and without an index buffer (Lab-04 Technique 1 vs Technique 2). Only V, I, "
          "instances and the exporter's byte counts are imported; every other column is an Excel formula, and the "
          "last column proves that the formulas reproduce the program's own numbers.", span=14)
    h = 4
    header(ws, h, GEOM_HDR, height=45)
    first, last = h + 1, h + len(prims)
    idx_cell = "$S$5"
    for i, p in enumerate(prims):
        r = first + i
        ok = f"ISNUMBER(D{r})"
        vals = [p["id"], p["type"], p["function"], _num(p["vertices"]), _num(p["indices"]),
                f'=IF({ok},E{r}/3,"n/a")', p["instances"], p["vertex_bytes"],
                f'=IF({ok},E{r}*H{r},"n/a")', f'=IF({ok},D{r}*H{r}+E{r}*{idx_cell},"n/a")',
                f'=IF({ok},1-J{r}/I{r},"n/a")', f'=IF({ok},E{r}/D{r},"n/a")', f'=IF({ok},F{r}*G{r},"n/a")',
                _num(p["bytes_indexed"]), _num(p["bytes_non_indexed"]),
                f'=IF({ok},IF(AND(J{r}=N{r},I{r}=O{r}),"match","MISMATCH"),"n/a")']
        fmts = [None, None, None, FMT_INT, FMT_INT, FMT_INT, FMT_INT, FMT_INT, FMT_INT, FMT_INT, FMT_PCT, "0.00",
                FMT_INT, FMT_INT, FMT_INT, None]
        for k, v in enumerate(vals):
            imported = k in (3, 4, 6, 7, 13, 14)
            put(ws, r, k + 1, v, fmts[k], INPUT_FILL if imported else None)
        ws.cell(row=r, column=2).fill = prim_fill(p["type"])
    t = last + 1
    put(ws, t, 1, "All", fill=TOTAL_FILL, font=BOLD)
    put(ws, t, 2, "All GPU meshes", fill=TOTAL_FILL, font=BOLD)
    put(ws, t, 3, "", fill=TOTAL_FILL)
    for c in (4, 5, 6, 7, 9, 10, 13, 14, 15):
        put(ws, t, c, f"=SUM({col(c)}{first}:{col(c)}{last})", FMT_INT, TOTAL_FILL, BOLD)
    put(ws, t, 8, "", fill=TOTAL_FILL)
    put(ws, t, 11, f"=1-J{t}/I{t}", FMT_PCT, TOTAL_FILL, BOLD)
    put(ws, t, 12, f"=E{t}/D{t}", "0.00", TOTAL_FILL, BOLD)
    put(ws, t, 16, f'=IF(COUNTIF(P{first}:P{last},"MISMATCH")=0,"all match","MISMATCH")', None, TOTAL_FILL, BOLD)
    ws.conditional_formatting.add(f"P{first}:P{t}", FormulaRule(formula=[f'EXACT(RIGHT(P{first},5),"match")'],
                                                                fill=PASS_FILL))
    ws.conditional_formatting.add(f"P{first}:P{t}", FormulaRule(formula=[f'P{first}="MISMATCH"'], fill=FAIL_FILL))
    section(ws, 3, 18, "Parameters")
    put(ws, 4, 18, "Index size (bytes), derived from the cube's exporter bytes", font=BOLD)
    put(ws, 5, 18, "GL_UNSIGNED_INT index")
    put(ws, 5, 19, f"=(N{first}-D{first}*H{first})/E{first}", FMT_INT)
    ctx["refs"]["tris_frame"] = f"'{S_GEOM}'!$M${t}"
    ctx["refs"]["gpu_bytes"] = f"'{S_GEOM}'!$J${t}"
    define_name(wb, "TrianglesPerFrame", S_GEOM, f"M{t}")
    _geom_charts(ws, first, last, t)
    widths(ws, [6, 18, 30, 11, 11, 11, 10, 9, 14, 14, 9, 9, 14, 13, 13, 12, 3, 30, 8])
    finish(ws, h)


def _geom_charts(ws, first, last, t):
    ch = BarChart()
    ch.type = "col"
    ch.title = "GPU memory per mesh: non-indexed vs indexed (bytes, log scale)"
    ch.y_axis.title = "bytes"
    ch.y_axis.scaling.logBase = 10
    ch.add_data(Reference(ws, min_col=9, max_col=10, min_row=4, max_row=last), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=2, min_row=first, max_row=last))
    ch.height, ch.width = 9, 18
    ws.add_chart(style_chart(ch), f"B{t + 3}")
    ch2 = BarChart()
    ch2.type = "bar"
    ch2.title = "Triangles submitted per frame, by primitive"
    ch2.add_data(Reference(ws, min_col=13, min_row=4, max_row=last), titles_from_data=True)
    ch2.set_categories(Reference(ws, min_col=2, min_row=first, max_row=last))
    ch2.legend = None
    ch2.height, ch2.width = 9, 16
    ws.add_chart(style_chart(ch2), f"J{t + 3}")
