def _num(v):
    return v if isinstance(v, (int, float)) else "n/a"


# ---- 1 Primitive Inventory ------------------------------------------------------------------------------
def _used_for(components, prim_type, limit=8):
    names = Counter(c["name"] for c in components if c["primitive"] == prim_type)
    top = [n for n, _ in names.most_common(limit)]
    more = len(names) - len(top)
    return ", ".join(top) + (f" (+{more} more)" if more > 0 else "")


